/** One block inside a section. Port of the Swift's `PrivacyContent` enum. */
internal sealed interface PrivacyContent {
    data class Paragraph(val text: String) : PrivacyContent
    data class Subheading(val title: String) : PrivacyContent
    data class Bullets(val items: List<String>) : PrivacyContent
}

/** Port of the Swift's `PrivacySection`. */
internal data class PrivacySection(
    val title: String,
    val body: List<PrivacyContent>,
)
